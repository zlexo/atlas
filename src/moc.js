// Generated maps. A hand-written index drifts the moment a note is added and
// nobody notices; a generated one is wrong only when the tags are, which is
// visible where the tags live.
//
// Rules, because this writes into the user's vault:
//  1. It writes only inside <vault>/Maps/Generated, and refuses a folder that
//     resolves anywhere else (a symlink out of the vault, say).
//  2. Every file it writes carries MARKER. A file there without the marker was
//     put there by a person: it is never removed and never overwritten.
import { writeFileSync, readFileSync, readdirSync, mkdirSync, existsSync, rmSync, realpathSync } from 'node:fs';
import { join, relative, isAbsolute } from 'node:path';

export const MARKER = '<!-- atlas:generated -->';
export const GENERATED = 'Maps/Generated';
export const FRONT = 'Generated Maps.md';
export const DUPLICATES = 'Duplicates.md';

const titleCase = t => t.replace(/[-_]/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
export const mapFile = tag => `${titleCase(tag)} Map.md`;
const noteName = e => e.provenance.path.replace(/^.*\//, '').replace(/\.md$/, '');
const link = e => e.source === 'vault' ? `[[${noteName(e)}]]` : `\`${e.id}\``;
const head = (extra = '') => `---\ntype: moc\ntags: [moc, generated]\ngenerated-by: atlas\n${extra}---\n${MARKER}\n\n`;

/** Vault notes by tag, without tags too rare to map or so common they map everything. */
export function groupByTag(entries, { min = 3, maxShare = 0.85 } = {}) {
  const notes = entries.filter(e => e.source === 'vault');
  const groups = new Map();
  for (const e of notes) for (const t of e.tags) {
    if (!groups.has(t)) groups.set(t, []);
    groups.get(t).push(e);
  }
  for (const [t, list] of groups) if (list.length < min || list.length > notes.length * maxShare) groups.delete(t);
  return groups;
}

export function renderMap(tag, list, total) {
  const folders = new Map();
  for (const e of list) {
    const dir = e.provenance.path.includes('/') ? e.provenance.path.split('/')[0] : 'Root';
    if (!folders.has(dir)) folders.set(dir, []);
    folders.get(dir).push(e);
  }
  const line = e => {
    const status = String(e.frontmatter.status ?? ''); // a short word is a column; a sentence is noise
    const others = e.tags.filter(t => t !== tag).slice(0, 3).map(t => `#${t}`).join(' ');
    return `- ${link(e)}${status && status.length <= 24 ? ` · *${status}*` : ''}${others ? ` · ${others}` : ''}`;
  };
  return head() + `# ${titleCase(tag)}\n\n**Generated by \`atlas moc\`. Do not edit: change the tags on the notes instead.**\n` +
    `${list.length} of ${total} vault notes carry \`#${tag}\`.\n\n` +
    [...folders].sort((a, b) => b[1].length - a[1].length).map(([dir, l]) =>
      `## ${dir} (${l.length})\n\n${l.slice().sort((a, b) => a.title.localeCompare(b.title)).map(line).join('\n')}`).join('\n\n') + '\n';
}

/** Every exact group and near pair, with its score. A report, not a refusal. */
export function renderDuplicates(dupes, entries, { threshold, minWords }) {
  const byId = new Map(entries.map(e => [e.id, e]));
  const l = id => byId.has(id) ? link(byId.get(id)) : `\`${id}\``;
  const exact = dupes.exact.map(g => `- ${g.map(l).join(' = ')}`);
  const near = dupes.near.slice().sort((a, b) => b.score - a.score).map(p => `| ${p.score.toFixed(3)} | ${l(p.a)} | ${l(p.b)} |`);
  return head() + '# Duplicates\n\n**Generated by `atlas moc`. Do not edit: merge the notes, or make one point at the other.**\n' +
    `Near means an 8-word shingle Jaccard of at least ${threshold}, over notes of ${minWords} words or more.\n\n` +
    `## Identical (${exact.length})\n\n${exact.join('\n') || 'None.'}\n\n` +
    `## Near (${near.length})\n\n${near.length ? `| Score | Note | Note |\n|---|---|---|\n${near.join('\n')}` : 'None.'}\n`;
}

/** The generated folder, checked to be inside the vault after symlinks resolve. */
export function generatedDir(vault) {
  const dir = join(vault, GENERATED);
  mkdirSync(dir, { recursive: true });
  const rel = relative(realpathSync(vault), realpathSync(dir));
  if (!rel || rel.startsWith('..') || isAbsolute(rel)) throw new Error(`${dir} resolves outside the vault; refusing to write`);
  return dir;
}

const generated = f => { try { return readFileSync(f, 'utf8').includes(MARKER); } catch { return false; } };

export function writeMaps({ entries, duplicates }, vault, { stamp, nearDuplicate, min = 3, maxShare = 0.85, dryRun = false }) {
  const dir = generatedDir(vault);
  const groups = [...groupByTag(entries, { min, maxShare })].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]));
  const total = entries.filter(e => e.source === 'vault').length;
  const pairs = duplicates.exact.length + duplicates.near.length;
  const files = new Map(groups.map(([t, list]) => [mapFile(t), renderMap(t, list, total)]));
  files.set(DUPLICATES, renderDuplicates(duplicates, entries, nearDuplicate));
  files.set(FRONT, head(stamp ? `built-from: ${stamp}\n` : '') + '# Generated maps\n\n' +
    '**Generated by `atlas moc`. Do not edit: change the tags on the notes instead.**\n' +
    `Every tag on at least ${min} of the ${total} vault notes, and on at most ${Math.round(maxShare * 100)}% of them, gets a map.\n\n` +
    groups.map(([t, l]) => `- [[${mapFile(t).slice(0, -3)}]] · ${l.length} notes`).join('\n') +
    `\n- [[${DUPLICATES.slice(0, -3)}]] · ${pairs} ${pairs === 1 ? 'pair' : 'pairs'}\n\nHand-written maps stay in \`Maps/\`; this tool never touches them.\n`);

  const removed = [], kept = [], written = [];
  for (const f of readdirSync(dir).filter(f => f.endsWith('.md') && !files.has(f) && generated(join(dir, f)))) {
    removed.push(f);
    if (!dryRun) rmSync(join(dir, f));
  }
  for (const [f, text] of files) {
    if (existsSync(join(dir, f)) && !generated(join(dir, f))) { kept.push(f); continue; } // a person's file
    written.push(f);
    if (!dryRun) writeFileSync(join(dir, f), text);
  }
  return { dir, written, removed, kept, maps: groups.map(([t, l]) => ({ tag: t, count: l.length })), pairs };
}
