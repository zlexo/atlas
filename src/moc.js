// Generated maps. A hand-written index drifts the moment a note is added and
// nobody notices; a generated one is wrong only when the tags are, which is
// visible where the tags live.
//
// Rules, because this writes into the user's vault:
//  1. It writes only inside <vault>/Maps/Generated. The folder is refused when
//     it, or the nearest part of its path that exists, resolves outside the
//     vault (a symlink out), and that is checked before anything is created.
//     Every file name is made from a tag by `mapFile`, which cannot produce a
//     path, and checked once more against the folder before each write.
//  2. Every file it writes carries MARKER. Anything else at a name it wants (a
//     file without the marker, a symlink, a folder) is a person's: it is never
//     removed, overwritten or written through.
//  3. One file that cannot be written is reported and the rest are written.
import { writeFileSync, readFileSync, readdirSync, mkdirSync, rmSync, realpathSync, lstatSync } from 'node:fs';
import { join, relative, isAbsolute, dirname, resolve } from 'node:path';

export const MARKER = '<!-- atlas:generated -->';
export const GENERATED = 'Maps/Generated';
export const FRONT = 'Generated Maps.md';
export const DUPLICATES = 'Duplicates.md';

const titleCase = t => t.replace(/[-_]/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
// Path separators, characters some file systems reserve, and control characters.
const UNSAFE = /[\\/:*?"<>|\x00-\x1f\x7f]/g;

/**
 * A tag's map file name, safe by construction: a nested tag `project/active`
 * becomes `Project - Active Map.md`; reserved characters become spaces; parts
 * that are only dots are dropped, so `../../x` is `X Map.md`; no leading dot.
 */
export function mapFile(tag) {
  const parts = String(tag).split('/').map(p => p.replace(UNSAFE, ' ').replace(/\s+/g, ' ').trim())
    .filter(p => p && !/^\.+$/.test(p)).map(titleCase);
  const name = parts.join(' - ').replace(/^[.\s]+/, '') || 'Tag';
  return `${name} Map.md`;
}

/** Names for every tag, unique without regard to case (the usual Mac and Windows disks), never a reserved name. */
export function mapFiles(tags) {
  const used = new Set([FRONT, DUPLICATES].map(f => f.toLowerCase()));
  const out = new Map();
  for (const t of tags) {
    let f = mapFile(t);
    for (let n = 2; used.has(f.toLowerCase()); n++) f = mapFile(t).replace(/ Map\.md$/, ` ${n} Map.md`);
    used.add(f.toLowerCase());
    out.set(t, f);
  }
  return out;
}

const noteName = e => e.provenance.path.replace(/^.*\//, '').replace(/\.md$/, '');
const link = e => e.source === 'vault' ? `[[${noteName(e)}]]` : `\`${e.id}\``;
const head = (extra = '') => `---\ntype: moc\ntags: [moc, generated]\ngenerated-by: atlas\n${extra}---\n${MARKER}\n\n`;
const oneLine = s => String(s).replace(/[\x00-\x1f\x7f]/g, ' ');

/** Vault notes by tag, without tags too rare to map or so common they map everything. */
export function groupByTag(entries, { min = 3, maxShare = 0.85 } = {}) {
  const notes = entries.filter(e => e.source === 'vault');
  const groups = new Map();
  for (const e of notes) for (const t of e.tags) {
    if (!groups.has(t)) groups.set(t, []);
    groups.get(t).push(e);
  }
  for (const [t, list] of groups) if (list.length < min || list.length > notes.length * maxShare) groups.delete(t);
  return groups;
}

export function renderMap(tag, list, total) {
  const folders = new Map();
  for (const e of list) {
    const dir = e.provenance.path.includes('/') ? e.provenance.path.split('/')[0] : 'Root';
    if (!folders.has(dir)) folders.set(dir, []);
    folders.get(dir).push(e);
  }
  const line = e => {
    const status = String(e.frontmatter.status ?? ''); // a short word is a column; a sentence is noise
    const others = e.tags.filter(t => t !== tag).slice(0, 3).map(t => `#${oneLine(t)}`).join(' ');
    return `- ${link(e)}${status && status.length <= 24 ? ` · *${status}*` : ''}${others ? ` · ${others}` : ''}`;
  };
  return head() + `# ${oneLine(titleCase(tag))}\n\n**Generated by \`atlas moc\`. Do not edit: change the tags on the notes instead.**\n` +
    `${list.length} of ${total} vault notes carry \`#${oneLine(tag)}\`.\n\n` +
    [...folders].sort((a, b) => b[1].length - a[1].length).map(([dir, l]) =>
      `## ${dir} (${l.length})\n\n${l.slice().sort((a, b) => a.title.localeCompare(b.title)).map(line).join('\n')}`).join('\n\n') + '\n';
}

/** Every exact group and near pair, with its score. A report, not a refusal. */
export function renderDuplicates(dupes, entries, { threshold, minWords }) {
  const byId = new Map(entries.map(e => [e.id, e]));
  const l = id => byId.has(id) ? link(byId.get(id)) : `\`${id}\``;
  const exact = dupes.exact.map(g => `- ${g.map(l).join(' = ')}`);
  const near = dupes.near.slice().sort((a, b) => b.score - a.score).map(p => `| ${p.score.toFixed(3)} | ${l(p.a)} | ${l(p.b)} |`);
  return head() + '# Duplicates\n\n**Generated by `atlas moc`. Do not edit: merge the notes, or make one point at the other.**\n' +
    `Near means an 8-word shingle Jaccard of at least ${threshold}, over notes of ${minWords} words or more.\n\n` +
    `## Identical (${exact.length})\n\n${exact.join('\n') || 'None.'}\n\n` +
    `## Near (${near.length})\n\n${near.length ? `| Score | Note | Note |\n|---|---|---|\n${near.join('\n')}` : 'None.'}\n`;
}

const lexists = p => { try { lstatSync(p); return true; } catch { return false; } };
const inside = (p, root, { self = true } = {}) => {
  const rel = relative(root, p);
  return rel === '' ? self : !rel.startsWith('..') && !isAbsolute(rel);
};

/**
 * The generated folder, created only after the nearest part of its path that
 * exists is known to resolve inside the vault, and checked again after.
 */
export function generatedDir(vault) {
  const root = realpathSync(vault);
  const dir = resolve(vault, GENERATED);
  let probe = dir;
  while (!lexists(probe)) probe = dirname(probe);
  let real;
  try { real = realpathSync(probe); } catch { throw new Error(`${probe} is a broken link; refusing to write`); }
  if (!inside(real, root)) throw new Error(`${dir} resolves outside the vault; refusing to write`);
  mkdirSync(dir, { recursive: true });
  if (!inside(realpathSync(dir), root, { self: false })) throw new Error(`${dir} resolves outside the vault; refusing to write`);
  return dir;
}

/** 'mine' for a regular file with the marker, 'none' when nothing is there, else 'theirs'. Never follows a link. */
function owner(f) {
  let st;
  try { st = lstatSync(f); } catch { return 'none'; }
  if (!st.isFile()) return 'theirs';
  try { return readFileSync(f, 'utf8').includes(MARKER) ? 'mine' : 'theirs'; } catch { return 'theirs'; }
}

export function writeMaps({ entries, duplicates }, vault, { stamp, nearDuplicate, min = 3, maxShare = 0.85, dryRun = false, namer = mapFiles }) {
  const dir = generatedDir(vault);
  const groups = [...groupByTag(entries, { min, maxShare })].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]));
  const names = namer(groups.map(([t]) => t)); // a test can pass a raw namer to reach the guard below
  const total = entries.filter(e => e.source === 'vault').length;
  const pairs = duplicates.exact.length + duplicates.near.length;
  const files = new Map(groups.map(([t, list]) => [names.get(t), renderMap(t, list, total)]));
  files.set(DUPLICATES, renderDuplicates(duplicates, entries, nearDuplicate));

  const removed = [], kept = [], written = [], errors = [];
  const attempt = (f, fn) => {
    // The last guard: whatever a name holds, the file must sit directly in the folder.
    if (dirname(resolve(dir, f)) !== dir) { errors.push({ file: f, error: 'not directly inside Maps/Generated; skipped' }); return; }
    try { fn(join(dir, f)); return true; } catch (e) { errors.push({ file: f, error: e.message }); }
  };
  for (const f of readdirSync(dir).filter(f => f.endsWith('.md') && !files.has(f) && f !== FRONT && owner(join(dir, f)) === 'mine'))
    if (dryRun || attempt(f, p => rmSync(p))) removed.push(f);
  const put = (f, text) => {
    if (owner(join(dir, f)) === 'theirs') { kept.push(f); return; } // a person's file, link or folder
    if (dryRun || attempt(f, p => writeFileSync(p, text))) written.push(f);
  };
  for (const [f, text] of files) put(f, text);

  // The front door last. It carries the stamp only when everything else was
  // written, so the status cannot call a half-written set current.
  const failed = errors.length ? `incomplete: ${errors.length}\n` : (stamp ? `built-from: ${stamp}\n` : '');
  put(FRONT, head(failed) + '# Generated maps\n\n' +
    '**Generated by `atlas moc`. Do not edit: change the tags on the notes instead.**\n' +
    `Every tag on at least ${min} of the ${total} vault notes, and on at most ${Math.round(maxShare * 100)}% of them, gets a map.\n\n` +
    groups.map(([t, l]) => `- [[${names.get(t).slice(0, -3)}]] · ${l.length} notes`).join('\n') +
    `\n- [[${DUPLICATES.slice(0, -3)}]] · ${pairs} ${pairs === 1 ? 'pair' : 'pairs'}\n\nHand-written maps stay in \`Maps/\`; this tool never touches them.\n` +
    (errors.length ? `\n## Not written\n\n${errors.map(e => `- \`${oneLine(e.file)}\`: ${oneLine(e.error)}`).join('\n')}\n` : ''));
  return { dir, written, removed, kept, errors, maps: groups.map(([t, l]) => ({ tag: t, file: names.get(t), count: l.length })), pairs };
}
